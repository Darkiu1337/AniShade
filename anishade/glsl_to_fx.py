class ConversionError(Exception):
    pass


@dataclass
class Block:
    description: str = ""
    bind: list[str] = field(default_factory=list)
    save: str = ""
    hook: str = "MAIN"
    components: int = 4
    width: str = ""
    height: str = ""
    body: str = ""


def split_blocks(text: str) -> tuple[str, list[Block]]:
    lines = text.splitlines()
    header: list[str] = []
    blocks: list[Block] = []
    current: Block | None = None
    body: list[str] = []

    def flush() -> None:
        nonlocal current, body
        if current is not None:
            current.body = "\n".join(body).strip()
            blocks.append(current)
        current, body = None, []

    for line in lines:
        stripped = line.strip()
        if stripped.startswith("//!DESC"):
            flush()
            current = Block(description=stripped[6:].strip())
            continue
        if stripped.startswith("//!"):
            if current is None:
                continue
            key, _, value = stripped[3:].partition(" ")
            value = value.strip()
            if key == "BIND":
                current.bind.append(value)
            elif key == "SAVE":
                current.save = value
            elif key == "HOOK":
                current.hook = value
            elif key == "COMPONENTS":
                current.components = int(value) if value.isdigit() else 4
            elif key == "WIDTH":
                current.width = value
            elif key == "HEIGHT":
                current.height = value
            continue
        if current is None:
            header.append(line)
        else:
            body.append(line)
    flush()
    return "\n".join(header).strip(), blocks


def _split_top_level(text: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    start = 0
    for index, char in enumerate(text):
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(text[start:index])
            start = index + 1
    parts.append(text[start:])
    return [part.strip() for part in parts if part.strip()]


def _matrix_constructor(name: str, args: list[str], operand: str | None = None) -> str:
    size = int(name[-1])
    expected = size * size
    if len(args) != expected:
        return f"float{size}x{size}({', '.join(args)})"
    # GLSL literals are column-major; the rows used by dot() are therefore
    # (a0, a4, a8, a12), (a1, a5, a9, a13), ...
    rows = [
        f"float{size}({', '.join(args[column * size + row] for column in range(size))})"
        for row in range(size)
    ]
    if operand and size == 4:
        return f"anishade_mul({', '.join(rows)}, {operand})"
    return f"float{size}x{size}({', '.join(rows)})"


def _read_operand(text: str, index: int) -> tuple[str | None, int]:
    """Read `* operand` after a matrix constructor. Returns (operand, new_index)."""
    while index < len(text) and text[index].isspace():
        index += 1
    if index >= len(text) or text[index] != "*":
        return None, index
    index += 1
    while index < len(text) and text[index].isspace():
        index += 1
    start = index
    while index < len(text) and (text[index].isalnum() or text[index] == "_"):
        index += 1
    if index == start:
        return None, start
    while index < len(text) and text[index].isspace():
        index += 1
    if index < len(text) and text[index] == "(":
        depth = 0
        while index < len(text):
            if text[index] == "(":
                depth += 1
            elif text[index] == ")":
                depth -= 1
                if depth == 0:
                    index += 1
                    break
            index += 1
    return text[start:index].strip(), index


def _convert_matrices(text: str) -> str:
    result: list[str] = []
    position = 0
    pattern = re.compile(r"\bmat([234])\s*\(")
    while True:
        match = pattern.search(text, position)
        if not match:
            result.append(text[position:])
            break
        result.append(text[position : match.start()])
        start = match.end()
        depth = 1
        index = start
        while index < len(text) and depth:
            if text[index] == "(":
                depth += 1
            elif text[index] == ")":
                depth -= 1
            index += 1
        if depth:
            raise ConversionError("unclosed parenthesis in matrix constructor")
        inner = text[start : index - 1]
        args = _split_top_level(inner)
        operand, end = _read_operand(text, index)
        if all(re.fullmatch(r"[-+0-9.eE, ]+", arg) for arg in args):
            result.append(_matrix_constructor(f"mat{match.group(1)}", args, operand))
            position = end if operand else index
        else:
            result.append(match.group(0) + inner + ")")
            position = index
    return "".join(result)


def to_hlsl(text: str) -> str:
    text = _convert_matrices(text)
    replacements = (
        (r"\bvec2\b", "float2"),
        (r"\bvec3\b", "float3"),
        (r"\bvec4\b", "float4"),
        (r"\bmat2\b", "float2x2"),
        (r"\bmat3\b", "float3x3"),
        (r"\bmat4\b", "float4x4"),
        (r"\bmix\s*\(", "lerp("),
        (r"\bfract\s*\(", "frac("),
        (r"\bmod\s*\(", "fmod("),
        (r"\binversesqrt\s*\(", "rsqrt("),
        (r"\btextureLod\s*\(", "tex2Dlod("),
        (r"\btexture\s*\(", "tex2D("),
        (r"\bdFdx\s*\(", "ddx("),
        (r"\bdFdy\s*\(", "ddy("),
    )
    for pattern, replacement in replacements:
        text = re.sub(pattern, replacement, text)
    return text


def _find_hook(body: str) -> tuple[str, str]:
    match = re.search(r"\bvec4\s+hook\s*\(\s*\)\s*\{", body)
    if not match:
        raise ConversionError("hook() function not found")
    start = match.end()
    depth = 1
    index = start
    while index < len(body) and depth:
        if body[index] == "{":
            depth += 1
        elif body[index] == "}":
            depth -= 1
        index += 1
    if depth:
        raise ConversionError("hook() missing closing brace")
    return body[: match.start()], body[start : index - 1]


def _split_helpers(prelude: str) -> tuple[list[str], list[str]]:
    """Separate global code from texture-dependent #defines."""
    global_lines: list[str] = []
    pass_defines: list[str] = []
    for line in prelude.splitlines():
        stripped = line.strip()
        if stripped.startswith("#define") and re.search(r"_(tex|texOff|pos)\b", stripped):
            pass_defines.append(line)
        else:
            global_lines.append(line)
    return global_lines, pass_defines


def _dedupe(text: str) -> str:
    seen: set[str] = set()
    output: list[str] = []
    for block in text.split("\n\n"):
        key = re.sub(r"\s+", " ", block.strip())
        if key and key not in seen:
            seen.add(key)
            output.append(block)
    return "\n\n".join(output)


def convert(text: str, source_name: str = "", technique: str | None = None) -> str:
    header, blocks = split_blocks(text)
    if not blocks:
        raise ConversionError("no //!DESC block found")

    technique_name = technique or Path(source_name).stem
    if not technique_name:
        raise ConversionError("missing technique name")

    # textures written by //!SAVE
    saved: dict[str, int] = {}
    for block in blocks:
        if block.save and block.save != "MAIN":
            saved[block.save] = max(saved.get(block.save, 1), block.components)

    # every texture a pass may sample
    bound_aliases: dict[str, str] = {}
    for block in blocks:
        for name in block.bind:
            if name in ("HOOKED", "PREKERNEL"):
                bound_aliases[name] = "sampInput"
                bound_aliases.setdefault("MAIN", "sampInput")
            elif name == "MAIN":
                bound_aliases["MAIN"] = "sampInput"
            else:
                if name not in saved:
                    raise ConversionError(f"BIND on unknown texture: {name}")
                bound_aliases[name] = f"samp{name}"
        if block.hook in ("MAIN", "PREKERNEL"):
            bound_aliases.setdefault("MAIN", "sampInput")

    macro_lines: list[str] = []
    for alias, sampler in bound_aliases.items():
        macro_lines.extend(
            [
                f"#define {alias}_texOff(o) tex2Dlod({sampler}, float4(clamp(pos + (o) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT), anishade_lo, anishade_hi), 0, 0))",
                f"#define {alias}_tex(p) tex2Dlod({sampler}, float4(clamp((p), anishade_lo, anishade_hi), 0, 0))",
                f"#define {alias}_pos clamp(pos, anishade_lo, anishade_hi)",
                f"#define {alias}_size float2(BUFFER_WIDTH, BUFFER_HEIGHT)",
                f"#define {alias}_pt float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT)",
            ]
        )
    macro_block = "\n".join(macro_lines)

    formats = {1: "R16F", 2: "RG16F", 3: "RGBA16F", 4: "RGBA16F"}

    declarations: list[str] = [BACKBUFFER]
    for name, components in saved.items():
        fmt = formats.get(components, "RGBA16F")
        declarations.append(
            f"texture {name}\n"
            "{\n"
            "    Width = BUFFER_WIDTH;\n"
            "    Height = BUFFER_HEIGHT;\n"
            f"    Format = {fmt};\n"
            "    MipLevels = 1;\n"
            "};\n"
            f"sampler samp{name}\n"
            "{\n"
            f"    Texture = {name};\n"
            + SAMPLER_BODY
            + "};\n"
        )

    global_code: list[str] = []
    pass_definitions: list[str] = []
    pass_functions: list[str] = []
    pass_state: list[str] = []

    for index, block in enumerate(blocks):
        prelude, hook_body = _find_hook(block.body)
        helpers, defines = _split_helpers(prelude)
        helper_text = to_hlsl("\n".join(helpers)).strip()
        if helper_text:
            global_code.append(helper_text)

        # ReShade compiles every pass in one translation unit: macro names must
        # be unique per pass (GLSL/mpv compiles each pass separately).
        define_names = {
            match.group(1)
            for line in defines
            if (match := re.match(r"\s*#define\s+(\w+)", line))
        }
        if define_names:
            prefix = f"P{index}_"
            names = sorted(define_names, key=len, reverse=True)

            def rename(text: str, names=names, pfx=prefix) -> str:
                for name in names:
                    text = re.sub(rf"\b{re.escape(name)}\b", pfx + name, text)
                return text

            defines = [to_hlsl(rename(line)) for line in defines]
            hook_body = rename(hook_body)

        pass_definitions.extend(defines)

        # textures visible to this pass
        bind_names: list[str] = []
        for name in block.bind:
            actual = "MAIN" if name in ("HOOKED", "PREKERNEL") else name
            if actual not in bind_names:
                bind_names.append(actual)
        if block.hook in ("MAIN", "PREKERNEL") and "MAIN" not in bind_names:
            bind_names.append("MAIN")
        for name in bind_names:
            if name not in bound_aliases:
                raise ConversionError(f"pass {index}: undeclared texture: {name}")

        body = to_hlsl(hook_body)
        is_final = block.save in ("", "MAIN")
        if is_final:
            # Final CNN pass writes quantized RGBA8 output + modified flag (alpha)
            # into texPrev1; PS_Present then blits texPrev1.rgb with opaque alpha=1.0
            # to the back buffer.
            body = re.sub(
                r"\breturn\s+([^;]+);",
                (
                    "{\n"
                    "        float3 anishade_out = saturate((\\1).rgb);\n"
                    "        float anishade_mod = anishade_maxdiff(anishade_out, anishade_src.rgb) >= (0.5 / 255.0) ? 1.0 : 0.0;\n"
                    "        return float4(anishade_out, anishade_mod);\n"
                    "    }"
                ),
                body,
            )
            # Temporal feedback guard: if this pixel was NOT redrawn by the game since
            # we shaded it (e.g. Chromium partial-present black bars, title bar, or
            # static VN frames), keep it as-is instead of re-filtering it into noise.
            body = (
                "    float4 anishade_src = tex2Dlod(sampInput, float4(pos, 0, 0));\n"
                "    if (anishade_src.a > 0.5)\n"
                "        return float4(anishade_src.rgb, 1.0);\n"
                "    if (pos.x < anishade_lo.x || pos.x > anishade_hi.x ||\n"
                "        pos.y < anishade_lo.y || pos.y > anishade_hi.y)\n"
                "        return float4(anishade_src.rgb, 0.0);\n"
                + body
            )
        # GLSL allows falling off the end of non-void helpers; HLSL does not.
        function = (
            f"float4 PS{index}(float4 position : SV_Position, float2 uv : TEXCOORD0) : SV_Target\n"
            "{\n"
            "    float2 pos = (floor(uv * float2(BUFFER_WIDTH, BUFFER_HEIGHT)) + 0.5) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);\n"
            + RECT_SETUP
            + "\n".join(defines)
            + "\n"
            + body
            + "\n}\n"
        )
        pass_functions.append(function)

        if is_final:
            target = "    RenderTarget0 = texPrev1;\n"
        elif block.save and block.save != "MAIN":
            target = f"    RenderTarget0 = {block.save};\n"
        else:
            target = ""
        pass_state.append(
            f"    pass p{index}\n"
            "    {\n"
            "        VertexShader = FullscreenVS;\n"
            f"        PixelShader = PS{index};\n"
            f"{target}"
            "    }\n"
        )

    if "getMedian" in text:
        for position, chunk in enumerate(pass_functions):
            if "getMedian" in chunk:
                pass_functions[position] = chunk
        global_code = [
            chunk.replace(
                "        }\n    }\n}",
                "        }\n    }\n\n    return v[0];\n}",
            )
            for chunk in global_code
        ]

    copy_function = (
        "float4 PS_Copy(float4 position : SV_Position, float2 uv : TEXCOORD0) : SV_Target\n"
        "{\n"
        "    float2 pos = (floor(uv * float2(BUFFER_WIDTH, BUFFER_HEIGHT)) + 0.5) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);\n"
        "    float4 c = tex2Dlod(sampMain, float4(pos, 0, 0));\n"
        "    // Guard against NaN/Inf/undefined pixels in the swap chain.\n"
        "    float3 safe_rgb = float3(\n"
        "        (c.r >= 0.0) ? min(c.r, 1.0) : 0.0,\n"
        "        (c.g >= 0.0) ? min(c.g, 1.0) : 0.0,\n"
        "        (c.b >= 0.0) ? min(c.b, 1.0) : 0.0\n"
        "    );\n"
        "    float4 p1 = tex2Dlod(sampPrev1, float4(pos, 0, 0));\n"
        "    float4 p2 = tex2Dlod(sampPrev2, float4(pos, 0, 0));\n"
        "    float4 p3 = tex2Dlod(sampPrev3, float4(pos, 0, 0));\n"
        "    float4 p4 = tex2Dlod(sampPrev4, float4(pos, 0, 0));\n"
        "    float eps = 0.4 / 255.0;\n"
        "    bool fb =\n"
        "        (p1.a > 0.5 && anishade_maxdiff(safe_rgb, p1.rgb) < eps) ||\n"
        "        (p2.a > 0.5 && anishade_maxdiff(safe_rgb, p2.rgb) < eps) ||\n"
        "        (p3.a > 0.5 && anishade_maxdiff(safe_rgb, p3.rgb) < eps) ||\n"
        "        (p4.a > 0.5 && anishade_maxdiff(safe_rgb, p4.rgb) < eps);\n"
        "    return float4(safe_rgb, fb ? 1.0 : 0.0);\n"
        "}\n"
        "\n"
        "float4 PS_Shift3(float4 position : SV_Position, float2 uv : TEXCOORD0) : SV_Target\n"
        "{\n"
        "    float2 pos = (floor(uv * float2(BUFFER_WIDTH, BUFFER_HEIGHT)) + 0.5) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);\n"
        "    return tex2Dlod(sampPrev3, float4(pos, 0, 0));\n"
        "}\n"
        "\n"
        "float4 PS_Shift2(float4 position : SV_Position, float2 uv : TEXCOORD0) : SV_Target\n"
        "{\n"
        "    float2 pos = (floor(uv * float2(BUFFER_WIDTH, BUFFER_HEIGHT)) + 0.5) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);\n"
        "    return tex2Dlod(sampPrev2, float4(pos, 0, 0));\n"
        "}\n"
        "\n"
        "float4 PS_Shift1(float4 position : SV_Position, float2 uv : TEXCOORD0) : SV_Target\n"
        "{\n"
        "    float2 pos = (floor(uv * float2(BUFFER_WIDTH, BUFFER_HEIGHT)) + 0.5) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);\n"
        "    return tex2Dlod(sampPrev1, float4(pos, 0, 0));\n"
        "}\n"
        "\n"
        "float4 PS_Present(float4 position : SV_Position, float2 uv : TEXCOORD0) : SV_Target\n"
        "{\n"
        "    float2 pos = (floor(uv * float2(BUFFER_WIDTH, BUFFER_HEIGHT)) + 0.5) * float2(BUFFER_RCP_WIDTH, BUFFER_RCP_HEIGHT);\n"
        "    return float4(tex2Dlod(sampPrev1, float4(pos, 0, 0)).rgb, 1.0);\n"
        "}\n"
    )
    copy_pass = (
        "    pass Copy\n"
        "    {\n"
        "        VertexShader = FullscreenVS;\n"
        "        PixelShader = PS_Copy;\n"
        "        RenderTarget0 = texInput;\n"
        "    }\n"
        "    pass Shift3\n"
        "    {\n"
        "        VertexShader = FullscreenVS;\n"
        "        PixelShader = PS_Shift3;\n"
        "        RenderTarget0 = texPrev4;\n"
        "    }\n"
        "    pass Shift2\n"
        "    {\n"
        "        VertexShader = FullscreenVS;\n"
        "        PixelShader = PS_Shift2;\n"
        "        RenderTarget0 = texPrev3;\n"
        "    }\n"
        "    pass Shift1\n"
        "    {\n"
        "        VertexShader = FullscreenVS;\n"
        "        PixelShader = PS_Shift1;\n"
        "        RenderTarget0 = texPrev2;\n"
        "    }\n"
    )
    present_pass = (
        "    pass Present\n"
        "    {\n"
        "        VertexShader = FullscreenVS;\n"
        "        PixelShader = PS_Present;\n"
        "    }\n"
    )

    parts = [
        header or "// MIT License",
        HEADER_NOTE,
        "\n".join(declarations),
        macro_block,
        MASK_DEFAULTS,
        FULLSCREEN_VS,
        MATRIX_HELPER,
        _dedupe("\n\n".join(global_code)),
        copy_function,
        "\n\n".join(pass_functions),
        f"technique {technique_name}\n{{\n" + copy_pass + "".join(pass_state) + present_pass + "}\n",
    ]
    return "\n".join(part for part in parts if part.strip()) + "\n"


def convert_file(source: Path, destination: Path) -> Path:
    text = source.read_text(encoding="utf-8")
    output = convert(text, source.name)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(output, encoding="utf-8", newline="\n")
    return destination

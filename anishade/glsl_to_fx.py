"""Translate Anime4K's MPV/GLSL shaders into self-contained ReShade FX (.fx).

ReShade only loads ReShade FX (``.fx``/``.addonfx``) effect files; the official
Anime4K release ships GLSL for MPV/libplacebo. This module converts the subset of
the MPV "generic shader" format used by the Anime4K Restore/Denoise/Clamp
families:

    //!DESC, //!HOOK, //!BIND, //!SAVE, //!WIDTH, //!HEIGHT, //!COMPONENTS
    vec4 hook() + helper functions + #define macros

Each GLSL pass becomes a ReShade FX pass; ``//!SAVE`` textures become render
targets; ``NAME_tex`` / ``NAME_texOff`` / ``NAME_pos`` become sampler macros.

Only same-size (restore/denoise) shaders are supported, which is exactly the
AniShade scope.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

HEADER_NOTE = (
    "// ReShade FX port generated by AniShade from the official Anime4K shader\n"
    "// (https://github.com/bloc97/Anime4K, MIT license). Do not edit by hand;\n"
    "// regenerate with tools/build_fx.py instead.\n"
)

FULLSCREEN_VS = """
void FullscreenVS(uint id : SV_VertexID, out float4 position : SV_Position, out float2 texcoord : TEXCOORD0)
{
    texcoord = float2((id << 1) & 2, id & 2);
    position = float4(texcoord * float2(2.0, -2.0) + float2(-1.0, 1.0), 0.0, 1.0);
}
"""

MATRIX_HELPER = """
// ReShade FX matrix constructors/multiplication are ambiguous across versions;
// expand the 4x4 multiply into four dot products (same approach as Magpie).
float4 anishade_mul(float4 r0, float4 r1, float4 r2, float4 r3, float4 v)
{
    return float4(dot(v, r0), dot(v, r1), dot(v, r2), dot(v, r3));
}

float anishade_maxdiff(float3 a, float3 b)
{
    float3 d = abs(a - b);
    return max(d.r, max(d.g, d.b));
}
"""

MASK_DEFAULTS = """
#ifndef ANISHADE_TOP_MARGIN
#define ANISHADE_TOP_MARGIN 0
#endif
#ifndef ANISHADE_CONTENT_ASPECT
#define ANISHADE_CONTENT_ASPECT 0.0
#endif
"""

#: Local variables used by the sampling macros below. Inserted in every pass.
RECT_SETUP = """
    float anishade_top = float(ANISHADE_TOP_MARGIN);
    float2 anishade_lo = float2(0.0, anishade_top / float(BUFFER_HEIGHT));
    float2 anishade_hi = float2(1.0, 1.0);
    if (ANISHADE_CONTENT_ASPECT > 0.0)
    {
        float avail_w = float(BUFFER_WIDTH);
        float avail_h = max(float(BUFFER_HEIGHT) - anishade_top, 1.0);
        float buffer_aspect = avail_w / avail_h;
        float content_w, content_h;
        if (buffer_aspect > ANISHADE_CONTENT_ASPECT)
        {
            content_h = avail_h;
            content_w = content_h * ANISHADE_CONTENT_ASPECT;
        }
        else
        {
            content_w = avail_w;
            content_h = content_w / ANISHADE_CONTENT_ASPECT;
        }
        float x0 = (avail_w - content_w) * 0.5;
        float y0 = anishade_top + (avail_h - content_h) * 0.5;
        anishade_lo = float2(x0 / float(BUFFER_WIDTH), y0 / float(BUFFER_HEIGHT));
        anishade_hi = float2((x0 + content_w) / float(BUFFER_WIDTH), (y0 + content_h) / float(BUFFER_HEIGHT));
        // Safety: a wrong/absurd aspect must never mask most of the screen.
        if ((anishade_hi.x - anishade_lo.x) * (anishade_hi.y - anishade_lo.y) < 0.25)
        {
            anishade_lo = float2(0.0, anishade_top / float(BUFFER_HEIGHT));
            anishade_hi = float2(1.0, 1.0);
        }
    }
"""

